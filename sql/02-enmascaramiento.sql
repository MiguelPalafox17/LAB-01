--CREAMOS UN ROLE LLAMADO SOPORTE CON LA CAPACIDAD DE INICIAR SESION
CREATE ROLE soporte NOLOGIN;

/* CREAMOS UNA VISATA LLAMADA "v_clientes_soporte" 
    CON EL CUAL SELECCIONAMOS TAN SOLO LOS CAMPOS 
    DE "ID" Y "NOMBRE" QUE PODRA VISUALIZAR, Y LOS 
    QUE TENDRAN ENMASCARAMIENTO CON CARACTERES ESPECIALES,
    SERAN LOS CAMPOS DE "CORREO", "TELEFONO", Y "RFC. 
    TODO ESTO PROVENIENTE DE LA TABLA "CLIENTES".
*/
CREATE VIEW v_clientes_soporte AS SELECT
    id,  nombre,CONCAT( LEFT(correo, 2),  '*****',  SUBSTRING(correo FROM POSITION('@' IN correo))) AS correo,CONCAT('******',RIGHT(telefono,4)) AS telefono,
CONCAT( '*********',RIGHT(rfc, 4)) AS rfc FROM clientes;

SELECT * FROM v_clientes_soporte; --CONSULTAMOS QUE LA VISTA SE HAYA CREADO CORRECTAMENTE

GRANT USAGE ON SCHEMA public TO soporte; --CREAMOS UN ESQUEMA PUBLICO PARA EL ROL DE SOPORTE
GRANT SELECT ON v_clientes_soporte TO soporte; --LE DAMOS ACCESO DE SOLO CONSULTA A LA VISTA "v_clientes_soporte" AL ROL DE "soporte"

REVOKE ALL ON clientes FROM soporte; --LE REVOCAMOS EL ACCESO A LA TABLA "clientes" AL ROL DE "soporte"

--VERIFICAMOS LOS RESULTADOS CON EL ROL DE "soporte"
SELECT * FROM v_clientes_soporte; --NOS MOSTRARA LA VISTA CON LOS DATOS ENMASCARADOS QUE SE ESPECIFICARON
