--AGRUPAMOS A LOS CLIENTES EN TRES RANGOS DE EDAD
SELECT CASE WHEN edad BETWEEN 18 AND 30 THEN '18-30' 
	WHEN edad BETWEEN 31 AND 45 THEN '31-45'
	ELSE '46+'   END AS rango_edad, COUNT(*) AS total 
FROM clientes GROUP BY 1;

--TOMAMOS SOLO LOS DOS PRIMEROS DIGITOS DEL CODIGO POSTAL
SELECT LEFT(codigo_postal, 2) AS region, 
	COUNT(*) AS total 
FROM clientes GROUP BY 1;

--COMBINAMOS LOS RESULTADOS DE LAS CONSULTAS ANTERIORES
SELECT CASE
	WHEN edad BETWEEN 18 AND 30 THEN '18-30'
	WHEN edad BETWEEN 31 AND 45 THEN '31-45'
	ELSE '46+' END AS rango_edad, LEFT(codigo_postal, 2) AS region,  COUNT(*) AS total
FROM clientes GROUP BY 1, 2;


--AGRUPAMOS A LOS CLIENTES POR LA EDAD Y REGION
SELECT CASE
	WHEN edad BETWEEN 18 AND 30 THEN '18-30'
	WHEN edad BETWEEN 31 AND 45 THEN '31-45'
	ELSE '46+'   END AS rango_edad,   LEFT(codigo_postal, 2) AS region, COUNT(*) AS total
FROM clientes GROUP BY 1, 2 HAVING COUNT(*) >= 5;


--AGRUPAMOS A LOS CLIENTES POR LA EDAD Y REGION PERO CON UN DIGITO DE SU CODIGO POSTAL
SELECT
    CASE
        WHEN edad BETWEEN 18 AND 49 THEN '18-49'
        ELSE '50+'
    END AS rango_edad,
    LEFT(codigo_postal, 1) AS region,
    COUNT(*) AS total
FROM clientes
GROUP BY 1, 2
HAVING COUNT(*) >= 5;